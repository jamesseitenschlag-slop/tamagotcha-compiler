/* =============================================================================
 * BANK 0 PAGE 1: BOOT & HARDWARE RESET
 * Power-on reset vector (0x0100), cold boot initialization, timer & watchdog setup
 * ============================================================================= */

#include "tama_types.h"

/* =============================================================================
 * Funktion:         0x0100 -> reset_vector()
 * Beschreibung:     CPU Power-On / Hardware-Reset Einstiegspunkt (PC=0x0100)
 * Runtime-Analyse:  1 dynamische Zyklen gemessen (0.0% CPU-Zeit)
 * Details:
 *   vec_reset  RESET vector
 *   addr 0x0100
 * ============================================================================= */
org(0x0100);
void reset_vector(void) {

    label_VEC_RESET:
    jp(0x10); // [0x0100] 0x010
    jp(0x16); // [0x0101] 0x016

    label_VEC_INT_CLOCK:
    jp(0x1D); // [0x0102] 0x01D
    jp(0x16); // [0x0103] 0x016

    label_VEC_INT_STOPWATCH:
    jp(0x16); // [0x0104] 0x016
    jp(0x16); // [0x0105] 0x016

    label_VEC_INT_K00:
    jp(0x16); // [0x0106] 0x016
    jp(0x16); // [0x0107] 0x016

    label_VEC_INT_K10:
    jp(0x16); // [0x0108] 0x016
    jp(0x16); // [0x0109] 0x016

    label_VEC_INT_SERIAL:
    jp(0x16); // [0x010A] 0x016
    jp(0x16); // [0x010B] 0x016

    label_VEC_INT_TIMER:
    jp(0x6F); // [0x010C] 0x06F
    jp(0x16); // [0x010D] 0x016
    jp(0x16); // [0x010E] 0x016
    jp(0x16); // [0x010F] 0x016

    label_INIT_STARTUP:
    rst(REG_F, 0x0); // [0x0110] 0xF50
    REG_A = 0xF; // [0x0111] 0xE0F
    REG_STACK_HIGH = REG_A; // [0x0112] 0xFE0
    REG_STACK_LOW = REG_A; // [0x0113] 0xFF0
    pset(0x02); // [0x0114] 0xE42
    jp(0x2A); // [0x0115] 0x02A
    push(REG_F); // [0x0116] 0xFCA
    push(REG_A); // [0x0117] 0xFC0
    push(REG_B); // [0x0118] 0xFC1
    push(REG_BANK_XP); // [0x0119] 0xFC4
    push(REG_PAGE_XH); // [0x011A] 0xFC5
    push(REG_OFFSET_XL); // [0x011B] 0xFC6
    jp(0x5B); // [0x011C] 0x05B
    push(REG_F); // [0x011D] 0xFCA
    push(REG_A); // [0x011E] 0xFC0
    push(REG_B); // [0x011F] 0xFC1
    push(REG_BANK_XP); // [0x0120] 0xFC4
    push(REG_PAGE_XH); // [0x0121] 0xFC5
    push(REG_OFFSET_XL); // [0x0122] 0xFC6
    rdf(); // [0x0123] 0xF5B
    REG_A = 0xF; // [0x0124] 0xE0F
    REG_BANK_XP = REG_A; // [0x0125] 0xE80
    REG_INDEX_X = 0x00; // [0x0126] 0xB00
    REG_A = REG_RAM_AT_X; // [0x0127] 0xEC2
    REG_INDEX_X = 0x76; // [0x0128] 0xB76
    lbpx(0x01); // [0x0129] 0x901
    lbpx(0x21); // [0x012A] 0x921
    REG_INDEX_X = 0x12; // [0x012B] 0xB12
    REG_RAM_AT_X = 0x1; // [0x012C] 0xE21
    REG_A = 0x0; // [0x012D] 0xE00
    REG_BANK_XP = REG_A; // [0x012E] 0xE80
    REG_INDEX_X = 0x57; // [0x012F] 0xB57
    cp(REG_RAM_AT_X, 0x0); // [0x0130] 0xDE0
    if (FLAG_ZERO) jp(0x33); // [0x0131] 0x633
    REG_RAM_AT_X = REG_RAM_AT_X + 0xF; // [0x0132] 0xC2F
    REG_INDEX_X = 0x3C; // [0x0133] 0xB3C
    cp(REG_RAM_AT_X, 0x0); // [0x0134] 0xDE0
    if (FLAG_ZERO) jp(0x4A); // [0x0135] 0x64A
    sdf(); // [0x0136] 0xF44
    REG_INDEX_X = 0x2E; // [0x0137] 0xB2E
    REG_RAM_AT_X = 0x1; // [0x0138] 0xE21
    REG_INDEX_X = 0x10; // [0x0139] 0xB10
    REG_RAM_AT_X = REG_RAM_AT_X + 0x1; // [0x013A] 0xC21
    REG_INDEX_X++; // [0x013B] 0xEE0
    REG_RAM_AT_X = adc(REG_RAM_AT_X, 0x0); // [0x013C] 0xC60
    cp(REG_RAM_AT_X, 0x6); // [0x013D] 0xDE6
    if (FLAG_CARRY) jp(0x49); // [0x013E] 0x249
    ldpx(REG_RAM_AT_X, 0x0); // [0x013F] 0xE60
    calz(0xE4); // [0x0140] 0x5E4
    if (FLAG_CARRY) jp(0x47); // [0x0141] 0x247
    REG_INDEX_X = 0x14; // [0x0142] 0xB14
    ldpx(REG_A, REG_RAM_AT_X); // [0x0143] 0xEE2
    ldpx(REG_B, REG_RAM_AT_X); // [0x0144] 0xEE6
    REG_INDEX_X = 0x14; // [0x0145] 0xB14
    call(0xF4); // [0x0146] 0x4F4
    pset(0x0C); // [0x0147] 0xE4C
    call(0x7A); // [0x0148] 0x47A
    rdf(); // [0x0149] 0xF5B
    REG_A = 0x0; // [0x014A] 0xE00
    REG_BANK_XP = REG_A; // [0x014B] 0xE80
    REG_INDEX_X = 0x2F; // [0x014C] 0xB2F
    REG_RAM_AT_X = REG_RAM_AT_X + 0x1; // [0x014D] 0xC21
    REG_INDEX_X++; // [0x014E] 0xEE0
    acpx(REG_RAM_AT_X, REG_A); // [0x014F] 0xF28
    REG_RAM_AT_X = adc(REG_RAM_AT_X, 0x0); // [0x0150] 0xC60
    if (!FLAG_CARRY) jp(0x5B); // [0x0151] 0x35B
    REG_A = 0xF; // [0x0152] 0xE0F
    REG_BANK_XP = REG_A; // [0x0153] 0xE80
    REG_INDEX_X = 0x70; // [0x0154] 0xB70
    fan(REG_RAM_AT_X, 0x3); // [0x0155] 0xDA3
    if (FLAG_ZERO) jp(0x5B); // [0x0156] 0x65B
    call(0xE5); // [0x0157] 0x4E5
    if (FLAG_ZERO) jp(0x5B); // [0x0158] 0x65B
    REG_INDEX_X = 0x70; // [0x0159] 0xB70
    REG_RAM_AT_X = 0x0; // [0x015A] 0xE20
    REG_A = 0x0; // [0x015B] 0xE00
    REG_BANK_XP = REG_A; // [0x015C] 0xE80
    REG_INDEX_X = 0x7D; // [0x015D] 0xB7D
    cp(REG_RAM_AT_X, 0x0); // [0x015E] 0xDE0
    if (FLAG_ZERO) jp(0x68); // [0x015F] 0x668
    pop(REG_OFFSET_XL); // [0x0160] 0xFD6
    pop(REG_PAGE_XH); // [0x0161] 0xFD5
    pop(REG_BANK_XP); // [0x0162] 0xFD4
    pop(REG_B); // [0x0163] 0xFD1
    pop(REG_A); // [0x0164] 0xFD0
    pop(REG_F); // [0x0165] 0xFDA
    ei(); // [0x0166] 0xF48
    return; // [0x0167] 0xFDF
    pop(REG_OFFSET_XL); // [0x0168] 0xFD6
    pop(REG_PAGE_XH); // [0x0169] 0xFD5
    pop(REG_BANK_XP); // [0x016A] 0xFD4
    pop(REG_B); // [0x016B] 0xFD1
    pop(REG_A); // [0x016C] 0xFD0
    pop(REG_F); // [0x016D] 0xFDA
    return; // [0x016E] 0xFDF
    push(REG_F); // [0x016F] 0xFCA
    push(REG_A); // [0x0170] 0xFC0
    push(REG_B); // [0x0171] 0xFC1
    push(REG_BANK_XP); // [0x0172] 0xFC4
    push(REG_PAGE_XH); // [0x0173] 0xFC5
    push(REG_OFFSET_XL); // [0x0174] 0xFC6
    rdf(); // [0x0175] 0xF5B
    call(0xA0); // [0x0176] 0x4A0
    REG_A = 0xF; // [0x0177] 0xE0F
    REG_BANK_XP = REG_A; // [0x0178] 0xE80
    REG_INDEX_X = 0x02; // [0x0179] 0xB02
    REG_A = REG_RAM_AT_X; // [0x017A] 0xEC2
    REG_INDEX_X = 0x40; // [0x017B] 0xB40
    REG_B = REG_RAM_AT_X; // [0x017C] 0xEC6
    REG_B = ~REG_B; // [0x017D] 0xD1F
    REG_B = REG_B & 0x7; // [0x017E] 0xC97
    REG_A = 0x0; // [0x017F] 0xE00
    REG_BANK_XP = REG_A; // [0x0180] 0xE80
    REG_INDEX_X = 0x5A; // [0x0181] 0xB5A
    REG_RAM_AT_X = REG_RAM_AT_X + 0x1; // [0x0182] 0xC21
    REG_INDEX_X = 0x22; // [0x0183] 0xB22
    REG_RAM_AT_X = REG_RAM_AT_X + 0xF; // [0x0184] 0xC2F
    REG_INDEX_X++; // [0x0185] 0xEE0
    REG_RAM_AT_X = adc(REG_RAM_AT_X, 0xF); // [0x0186] 0xC6F
    if (FLAG_CARRY) jp(0x8A); // [0x0187] 0x28A
    REG_INDEX_X = 0x22; // [0x0188] 0xB22
    lbpx(0x00); // [0x0189] 0x900
    REG_INDEX_X = 0x26; // [0x018A] 0xB26
    REG_A = REG_RAM_AT_X; // [0x018B] 0xEC2
    ldpx(REG_RAM_AT_X, REG_B); // [0x018C] 0xEE9
    REG_A = REG_A ^ REG_B; // [0x018D] 0xAE1
    REG_A = REG_A & REG_B; // [0x018E] 0xAC1
    REG_RAM_AT_X = REG_RAM_AT_X | REG_A; // [0x018F] 0xAD8
    REG_INDEX_X = 0x3D; // [0x0190] 0xB3D
    cp(REG_RAM_AT_X, REG_B); // [0x0191] 0xF09
    if (FLAG_ZERO) jp(0x97); // [0x0192] 0x697
    REG_RAM_AT_X = REG_B; // [0x0193] 0xEC9
    REG_INDEX_X = 0x3E; // [0x0194] 0xB3E
    REG_RAM_AT_X = 0x0; // [0x0195] 0xE20
    jp(0x9F); // [0x0196] 0x09F
    REG_INDEX_X = 0x3E; // [0x0197] 0xB3E
    REG_RAM_AT_X = REG_RAM_AT_X + 0x1; // [0x0198] 0xC21
    if (!FLAG_ZERO) jp(0x9F); // [0x0199] 0x79F
    REG_RAM_AT_X = 0x8; // [0x019A] 0xE28
    REG_INDEX_X = 0x3F; // [0x019B] 0xB3F
    REG_B = REG_B & REG_RAM_AT_X; // [0x019C] 0xAC6
    REG_INDEX_X = 0x27; // [0x019D] 0xB27
    REG_RAM_AT_X = REG_RAM_AT_X | REG_B; // [0x019E] 0xAD9
    jp(0x5B); // [0x019F] 0x05B
    REG_A = 0x0; // [0x01A0] 0xE00
    REG_BANK_XP = REG_A; // [0x01A1] 0xE80
    REG_INDEX_X = 0x32; // [0x01A2] 0xB32
    REG_RAM_AT_X = REG_RAM_AT_X + 0xF; // [0x01A3] 0xC2F
    REG_INDEX_X++; // [0x01A4] 0xEE0
    REG_RAM_AT_X = adc(REG_RAM_AT_X, 0xF); // [0x01A5] 0xC6F
    if (!FLAG_CARRY) jp(0xAB); // [0x01A6] 0x3AB
    REG_INDEX_X = 0x34; // [0x01A7] 0xB34
    fan(REG_RAM_AT_X, 0x8); // [0x01A8] 0xDA8
    if (!FLAG_ZERO) jp(0xD7); // [0x01A9] 0x7D7
    return; // [0x01AA] 0xFDF
    REG_INDEX_X = 0x36; // [0x01AB] 0xB36
    REG_A = REG_RAM_AT_X; // [0x01AC] 0xEC2
    REG_RAM_AT_X = REG_RAM_AT_X + 0x2; // [0x01AD] 0xC22
    REG_INDEX_X++; // [0x01AE] 0xEE0
    REG_B = REG_RAM_AT_X; // [0x01AF] 0xEC6
    REG_RAM_AT_X = adc(REG_RAM_AT_X, 0x0); // [0x01B0] 0xC60
    REG_INDEX_X = 0x32; // [0x01B1] 0xB32
    pset(0x0E); // [0x01B2] 0xE4E
    call(0x7C); // [0x01B3] 0x47C
    cp(REG_OFFSET_XL, 0x6); // [0x01B4] 0xA56
    if (FLAG_ZERO) jp(0xC1); // [0x01B5] 0x6C1
    REG_INDEX_X = 0x59; // [0x01B6] 0xB59
    cp(REG_RAM_AT_X, 0xF); // [0x01B7] 0xDEF
    if (FLAG_ZERO) jp(0xC1); // [0x01B8] 0x6C1
    REG_INDEX_X = 0x58; // [0x01B9] 0xB58
    REG_RAM_AT_X = REG_RAM_AT_X + 0xF; // [0x01BA] 0xC2F
    REG_INDEX_X++; // [0x01BB] 0xEE0
    REG_RAM_AT_X = adc(REG_RAM_AT_X, 0xF); // [0x01BC] 0xC6F
    if (FLAG_CARRY) jp(0xC1); // [0x01BD] 0x2C1
    REG_INDEX_X = 0x36; // [0x01BE] 0xB36
    lbpx(0x7D); // [0x01BF] 0x97D
    jp(0xAB); // [0x01C0] 0x0AB
    REG_INDEX_X = 0x34; // [0x01C1] 0xB34
    fan(REG_RAM_AT_X, 0x8); // [0x01C2] 0xDA8
    if (!FLAG_ZERO) jp(0xD7); // [0x01C3] 0x7D7
    REG_INDEX_X = 0x38; // [0x01C4] 0xB38
    lbpx(0x58); // [0x01C5] 0x958
    REG_A = 0xF; // [0x01C6] 0xE0F
    REG_BANK_XP = REG_A; // [0x01C7] 0xE80
    REG_INDEX_X = 0x71; // [0x01C8] 0xB71
    REG_RAM_AT_X = REG_RAM_AT_X | 0x1; // [0x01C9] 0xCE1
    push(REG_BANK_XP); // [0x01CA] 0xFC4
    REG_A = 0x0; // [0x01CB] 0xE00
    REG_BANK_XP = REG_A; // [0x01CC] 0xE80
    REG_INDEX_X = 0x34; // [0x01CD] 0xB34
    ldpx(REG_A, REG_RAM_AT_X); // [0x01CE] 0xEE2
    REG_B = REG_RAM_AT_X; // [0x01CF] 0xEC6
    pop(REG_BANK_XP); // [0x01D0] 0xFD4
    REG_INDEX_X = 0x74; // [0x01D1] 0xB74
    ldpx(REG_RAM_AT_X, REG_A); // [0x01D2] 0xEE8
    REG_RAM_AT_X = REG_B; // [0x01D3] 0xEC9
    REG_INDEX_X = 0x54; // [0x01D4] 0xB54
    REG_RAM_AT_X = REG_RAM_AT_X & 0x7; // [0x01D5] 0xCA7
    return; // [0x01D6] 0xFDF
    REG_INDEX_X = 0x38; // [0x01D7] 0xB38
    REG_RAM_AT_X = REG_RAM_AT_X + 0xF; // [0x01D8] 0xC2F
    REG_INDEX_X++; // [0x01D9] 0xEE0
    REG_RAM_AT_X = adc(REG_RAM_AT_X, 0xF); // [0x01DA] 0xC6F
    REG_A = 0xF; // [0x01DB] 0xE0F
    REG_BANK_XP = REG_A; // [0x01DC] 0xE80
    if (FLAG_CARRY) jp(0xE0); // [0x01DD] 0x2E0
    REG_INDEX_X = 0x71; // [0x01DE] 0xB71
    REG_RAM_AT_X = REG_RAM_AT_X & 0xE; // [0x01DF] 0xCAE
    REG_INDEX_X = 0x54; // [0x01E0] 0xB54
    REG_RAM_AT_X = REG_RAM_AT_X | 0x8; // [0x01E1] 0xCE8
    return; // [0x01E2] 0xFDF
    REG_A = 0xF; // [0x01E3] 0xE0F
    REG_BANK_XP = REG_A; // [0x01E4] 0xE80
    REG_INDEX_X = 0x73; // [0x01E5] 0xB73
    REG_RAM_AT_X = 0x6; // [0x01E6] 0xE26
    nop5(); // [0x01E7] 0xFFB
    REG_A = REG_RAM_AT_X; // [0x01E8] 0xEC2
    REG_RAM_AT_X = 0x0; // [0x01E9] 0xE20
    REG_A = REG_A & 0x8; // [0x01EA] 0xC88
    return; // [0x01EB] 0xFDF
    REG_INDEX_X = 0x75; // [0x01EC] 0xB75
    ldpx(REG_RAM_AT_X, 0x0); // [0x01ED] 0xE60
    ldpx(REG_RAM_AT_X, REG_A); // [0x01EE] 0xEE8
    ldpx(REG_RAM_AT_X, REG_B); // [0x01EF] 0xEE9
    REG_INDEX_X = 0x57; // [0x01F0] 0xB57
    ldpx(REG_RAM_AT_X, REG_B); // [0x01F1] 0xEE9
    calz(0x21); // [0x01F2] 0x521
    return; // [0x01F3] 0xFDF
    REG_A = REG_A + 0x1; // [0x01F4] 0xC01
    REG_B = adc(REG_B, 0x0); // [0x01F5] 0xC50
    cp(REG_B, 0x1); // [0x01F6] 0xDD1
    if (FLAG_CARRY) jp(0xFD); // [0x01F7] 0x2FD
    if (!FLAG_ZERO) jp(0xFB); // [0x01F8] 0x7FB
    cp(REG_A, 0x8); // [0x01F9] 0xDC8
    if (FLAG_CARRY) jp(0xFD); // [0x01FA] 0x2FD
    REG_A = 0x0; // [0x01FB] 0xE00
    REG_B = 0x0; // [0x01FC] 0xE10
    ldpx(REG_RAM_AT_X, REG_A); // [0x01FD] 0xEE8
    ldpx(REG_RAM_AT_X, REG_B); // [0x01FE] 0xEE9
    return; // [0x01FF] 0xFDF
// ----------------------------------------------------------------------
// BANK 0, PAGE 0x2 (Basis 0x0200)
// ----------------------------------------------------------------------
}
