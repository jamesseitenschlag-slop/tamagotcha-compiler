// compile_c: C source -> assembly text (+variable info)
// ===========================================================================
static string compile_c(const string& src, vector<string>& varInfo) {
    vector<Tok> toks = tokenize(src);
    Parser parser(std::move(toks));
    Node prog = parser.parse_program();
    Gen gen;
    gen.gen_all(prog);
    // header comment
    string asmText = "; generated by c_compiler for the E0C6S46\n; variables: ";
    {
        string list;
        for (auto& n : gen.varOrder) {
            if (!list.empty()) list += ", ";
            char b[64];
            snprintf(b, sizeof b, "%s@0x%02X", n.c_str(),
                     gen.vars[n].first);
            list += b;
        }
        asmText += list + "\n";
    }
    for (auto& l : gen.finalAsm) asmText += l + "\n";
    for (auto& kv : gen.vars) {
        char b[32];
        snprintf(b, sizeof b, "%s=0x%02X", kv.first.c_str(), kv.second.first);
        varInfo.push_back(b);
    }
    return asmText;
}

